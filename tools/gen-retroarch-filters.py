#!/usr/bin/env python3
"""Writes Sources/SMLauncherPlusKit/RetroArchCatalog.swift: the RetroArch filters the launcher offers (S-014),
pinned to one commit of github.com/libretro/glsl-shaders, with every file each preset needs and its SHA-256.

Usage: tools/gen-retroarch-filters.py <clone of libretro/glsl-shaders>
Each filter here was tried in the game first (docs/STORIES.md, S-014). Add one only after it has.
"""
import hashlib, os, re, subprocess, sys

# (id, name shown in Settings, preset path in the repo)
FILTERS = [
    ("crt-lottes", "CRT-Lottes", "crt/crt-lottes.glslp"),
    ("crt-geom", "CRT-Geom", "crt/crt-geom.glslp"),
    ("crt-easymode-halation", "CRT-Easymode Halation", "crt/crt-easymode-halation.glslp"),
    ("crt-mattias", "CRT-Mattias", "crt/crt-mattias.glslp"),
    ("zfast-crt", "zfast-CRT", "crt/zfast-crt.glslp"),
    ("lcd3x", "LCD3x", "handheld/lcd3x.glslp"),
    ("hq4x", "HQ4x", "hqx/hq4x.glslp"),
    ("xbrz-freescale", "xBRZ Freescale", "xbrz/xbrz-freescale.glslp"),
]

def value(text, key):
    m = re.search(r'^\s*' + re.escape(key) + r'\s*=\s*"?([^"\n]*?)"?\s*$', text, re.M)
    return m.group(1).strip() if m else None

def closure(repo, preset):
    files, todo = set([preset]), []
    text = open(os.path.join(repo, preset)).read()
    base = os.path.dirname(preset)
    count = int(value(text, "shaders") or 0)
    for i in range(count):
        todo.append(os.path.normpath(os.path.join(base, value(text, f"shader{i}"))))
    for name in (value(text, "textures") or "").split(";"):
        if name.strip():
            files.add(os.path.normpath(os.path.join(base, value(text, name.strip()))))
    while todo:
        path = todo.pop()
        if path in files: continue
        files.add(path)
        for inc in re.findall(r'^\s*#include\s+"([^"]+)"', open(os.path.join(repo, path), errors="ignore").read(), re.M):
            todo.append(os.path.normpath(os.path.join(os.path.dirname(path), inc)))
    for f in files:
        if not os.path.isfile(os.path.join(repo, f)): sys.exit(f"missing {f} for {preset}")
    return sorted(files)

def main():
    repo = sys.argv[1]
    commit = subprocess.check_output(["git", "-C", repo, "rev-parse", "HEAD"], text=True).strip()
    out = ["// Generated by tools/gen-retroarch-filters.py. Don't edit; run the script.", "",
           "extension RetroArchFilter {",
           f'    /// The commit of github.com/libretro/glsl-shaders the files come from.',
           f'    public static let commit = "{commit}"', "",
           "    public static let all: [RetroArchFilter] = ["]
    for fid, name, preset in FILTERS:
        out.append(f'        RetroArchFilter(id: "{fid}", name: "{name}", preset: "{preset}", files: [')
        for f in closure(repo, preset):
            data = open(os.path.join(repo, f), "rb").read()
            out.append(f'            .init(path: "{f}", sha256: "{hashlib.sha256(data).hexdigest()}", size: {len(data)}),')
        out.append("        ]),")
    out += ["    ]", "}", ""]
    target = os.path.join(os.path.dirname(__file__), "..", "Sources", "SMLauncherPlusKit", "RetroArchCatalog.swift")
    open(target, "w").write("\n".join(out))
    print(f"wrote {len(FILTERS)} filters at {commit[:7]}")

main()
